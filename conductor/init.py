"""`conductor init` — scaffold a workspace so a stranger can start in one command.

Conductor ships with no data: it needs a workspace (the projects it manages) and a few
files. `init` discovers what it can and writes only what is missing — it never
overwrites or deletes. The files it creates, and the settings it leaves empty, come from
the same schema (`conductor.settings`), so the "what do I plug in?" answer is generated,
not written by hand.

    python -m conductor init                 # scaffold using env/config/default paths
    python -m conductor init --workspace ~/Work
    python -m conductor init --dry-run       # show the plan, write nothing

Non-destructive by design: a file that exists is reported as "kept", never replaced.
For an existing workspace, `init` generates the registry by scanning the disk; run
`conductor reconcile` afterward to check reality against it.
"""

from __future__ import annotations

import sys
from pathlib import Path

from conductor import config, settings

_HEADER = "# {name} — generated by `conductor init`. Edit by hand; git tracks it.\n\n"

_REGISTRY_HEAD = """# Workspace registry — single source of truth for every project.
#
# Generated by `conductor init` by scanning the workspace, then hand-edited. Live state
# (last commit, dirty files, service up/down) is derived — never put it here.
#   domain : life | film | politics | machine
#   kind   : product | tool | experiment | record
#   status : active | maintenance | dormant | archived
#   tier   : public | personal | infra
#   deploy : local | <production-host> | github-pages | none
#
# Check reality vs. this file:  python -m conductor reconcile
"""


def _write_if_absent(path: Path, content: str, action: str, dry: bool) -> str:
    """Create the file only when absent. Returns a one-line report."""
    if path.exists():
        return f"kept    {path}"
    if not dry:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return f"created {path}  ({action})"


def _config_toml(ws: Path) -> str:
    """A commented config.toml: discovered values set, the optional slots shown empty."""
    lines = [
        "# Machine-specific conductor settings. Every value here is optional; the shipped",
        "# defaults are empty, so an unset integration is reported as *unavailable*.",
        "# `regulator config` prints this list with what each slot enables.",
        "",
        f'workspace_root = "{ws}"',
        "",
        "# Paths below default relative to workspace_root. Set one only to point elsewhere.",
    ]
    for s in settings.SLOTS:
        if s.key == "workspace_root":
            continue
        if s.default:
            value = s.default.format(home=str(Path.home()), workspace=str(ws), app=str(config.app_dir()))
            lines.append(f"#{s.key} = {value!r}   # default; {s.enables}")
        elif s.kind in ("list", "table"):
            lines.append(f"# {s.key} — {s.enables} (e.g. {s.example or '...'})")
        else:
            lines.append(f"#{s.key} = {s.example!r}   # unset; enables {s.enables}")
    lines.append("")
    return "\n".join(lines)


def _scan_projects(ws: Path) -> list[str]:
    """Project directory names under work/apps and work/research (sorted, hidden skipped)."""
    names: list[str] = []
    for base in ("work/apps", "work/research"):
        d = ws / base
        if not d.is_dir():
            continue
        for child in sorted(d.iterdir()):
            if child.is_dir() and not child.name.startswith("."):
                names.append(child.name)
    return names


def _registry_toml(ws: Path, names: list[str]) -> str:
    if not names:
        return _REGISTRY_HEAD + "\n# No projects found under work/apps or work/research.\n"
    blocks = [_REGISTRY_HEAD]
    for name in names:
        blocks.append(
            f'[[project]]\nname = "{name}"\ntitle = "{name}"\nstatus = "active"\n'
            f'tier = "personal"\ndomain = "machine"\nkind = "tool"\ndeploy = "none"\n'
        )
    return "\n".join(blocks)


def main(argv: list[str] | None = None) -> int:
    argv = list(argv if argv is not None else sys.argv[1:])
    dry = "--dry-run" in argv
    ws_arg = None
    if "--workspace" in argv:
        i = argv.index("--workspace")
        if i + 1 < len(argv):
            ws_arg = Path(argv[i + 1]).expanduser()

    ws = ws_arg or _resolve_workspace()
    ws = ws.resolve()

    print(f"regulator init — workspace {ws}{'  (dry-run)' if dry else ''}\n")
    reports: list[str] = []

    # 1. the workspace and its marker
    if not ws.is_dir():
        if not dry:
            ws.mkdir(parents=True)
        reports.append(f"created {ws}  (workspace root)")
    reports.append(_write_if_absent(ws / ".workspace-root", "", "workspace marker", dry))

    # 2. the data files (only when absent)
    reports.append(_write_if_absent(config.app_dir() / "config.toml", _config_toml(ws), "settings", dry))
    reports.append(_write_if_absent(config.app_dir() / "policy.json", '{"mode": "standard"}\n', "policy", dry))
    reports.append(
        _write_if_absent(ws / "registry" / "registry.toml", _registry_toml(ws, _scan_projects(ws)), "projects", dry)
    )
    reports.append(
        _write_if_absent(
            ws / "fleet.toml",
            _HEADER.format(name="fleet.toml") + "# [[service]] blocks — see `python -m conductor fleet`\n",
            "services",
            dry,
        )
    )

    for r in reports:
        print("  " + r)

    # 3. what still needs plugging in — the generated checklist
    print()
    missing = settings.unset()
    if missing:
        print(f"Next: {len(missing)} optional integration(s) are unconfigured.")
        print("Run `regulator config` to see each slot and what it enables.")
    else:
        print("All core integrations configured.")
    print("Then: `regulator projects reconcile` (check the registry) and `regulator brief`.")
    return 0


def _resolve_workspace() -> Path:
    from conductor import projects

    return projects.workspace_root() or (Path.home() / "Workspace")
