"""Render the workspace registry into human-readable docs.

Ported from registry/render.py (Track A2.2). Logic is verbatim; only the path math
changed (find_workspace_root()/registry_path()). Source of truth is registry.toml;
live git state is read fresh so output can never drift. Writes:

  - registry/REGISTRY.md   (full generated index, owned entirely by this script)
  - README.md              (the block between the GENERATED markers only)

Usage:  python3 -m conductor projects render           # write the docs
        python3 -m conductor projects render --check    # exit 1 if stale (CI/pre-commit)
"""

from __future__ import annotations

import subprocess
import sys
import tomllib
from datetime import date
from pathlib import Path

from conductor.projects import find_workspace_root, locate, registry_path

BEGIN, END = "<!-- BEGIN GENERATED: registry/render.py -->", "<!-- END GENERATED -->"


# Paths are *functions* (read the environment at call time) so a redirect set after
# import still applies — the testability bug that comes from import-time capture.
def _root() -> Path:
    return find_workspace_root()


def _reg() -> Path:
    return registry_path()


def _registry_md() -> Path:
    return _root() / "registry" / "REGISTRY.md"


def _readme() -> Path:
    return _root() / "README.md"


def targets() -> tuple[Path, Path]:
    """The two generated files this module owns (registry index + README block)."""
    return _registry_md(), _readme()


STATUS_ORDER = ["active", "maintenance", "dormant", "empty", "vendor", "archived"]
STATUS_EMOJI = {"active": "🟢", "maintenance": "🔵", "dormant": "🟡", "empty": "⚪", "vendor": "📦", "archived": "🗄️"}


def git(project_dir: Path, *args: str) -> str:
    try:
        out = subprocess.run(["git", "-C", str(project_dir), *args], capture_output=True, text=True, timeout=15)
        return out.stdout.strip()
    except Exception:
        return ""


def live_state(name: str) -> dict:
    """Fresh git facts for a local project dir (empty dict if not a repo)."""
    d = locate(name)
    if d is None:
        return {"exists": False, "git": False}
    if not (d / ".git").is_dir():
        return {"exists": True, "git": False}
    dirty = git(d, "status", "--porcelain")
    return {
        "exists": True,
        "git": True,
        "branch": git(d, "rev-parse", "--abbrev-ref", "HEAD"),
        "last": git(d, "log", "-1", "--format=%cd", "--date=short"),
        "dirty": len([x for x in dirty.splitlines() if x.strip()]),
    }


def load():
    with _reg().open("rb") as fh:
        data = tomllib.load(fh)
    return data.get("meta", {}), data.get("project", [])


def render_registry(meta: dict, projects: list) -> str:
    today = date.today().isoformat()
    host = meta.get("production_host", "?")
    lines = [
        "# Workspace Registry",
        "",
        f"_Generated by `registry/render.py` on {today}. Do not edit by hand — "
        f"edit `registry/registry.toml` and re-run._",
        "",
        f"Production host: **{host}** (ssh). Apps bind `127.0.0.1` behind Cloudflare tunnels.",
        "",
    ]

    by_status: dict[str, list] = {}
    for p in projects:
        by_status.setdefault(p.get("status", "?"), []).append(p)

    for status in STATUS_ORDER:
        group = by_status.get(status)
        if not group:
            continue
        lines.append(f"## {STATUS_EMOJI.get(status, '')} {status.title()}")
        lines.append("")
        # The domain is the *project*; a row is one app. Grouping by domain inside each
        # status bucket is what makes "life administration" visible as one effort
        # instead of five unrelated rows — and keeps the status, which is the scope
        # instruction an agent reads first, as the outer key.
        lines.append("| App | Domain | Kind | Tier | What it is | Deploy | URL | Last commit | Branch | Uncommitted |")
        lines.append("|---|---|---|---|---|---|---|---|---|---|")
        for p in sorted(
            group,
            key=lambda x: (x.get("domain", "~"), x.get("tier", ""), x["name"]),
        ):
            s = live_state(p["name"])
            url = p.get("url") or ""
            url_cell = f"[{url.replace('https://', '')}]({url})" if url else "—"
            deploy = p.get("deploy", "")
            if not s.get("exists"):
                last, branch, dirty = "_no local dir_", "—", "—"
            elif not s.get("git"):
                last, branch, dirty = "_no git_", "—", "—"
            else:
                last = s["last"] or "?"
                branch = s["branch"] or "?"
                n = s["dirty"]
                dirty = "0" if n == 0 else f"**{n}** ⚠️"
            lines.append(
                f"| `{p['name']}` | {p.get('domain', '')} | {p.get('kind', '')} | {p.get('tier', '')} | {p.get('title', '')} | {deploy} | {url_cell} "
                f"| {last} | {branch} | {dirty} |"
            )
        lines.append("")

    # Notes section — surface the per-project notes so they aren't buried in TOML.
    noted = [p for p in projects if p.get("notes")]
    if noted:
        lines.append("## Notes & flags")
        lines.append("")
        for p in sorted(noted, key=lambda x: (STATUS_ORDER.index(x.get("status", "archived")), x["name"])):
            lines.append(f"- **{p['name']}** — {p['notes']}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_readme_block(meta: dict, projects: list) -> str:
    counts: dict[str, int] = {}
    for p in projects:
        counts[p.get("status", "?")] = counts.get(p.get("status", "?"), 0) + 1
    summary = " · ".join(f"{STATUS_EMOJI.get(s, '')} {counts[s]} {s}" for s in STATUS_ORDER if s in counts)
    live = [p for p in projects if p.get("deploy") == meta.get("production_host") and p.get("url")]
    lines = [
        BEGIN,
        "",
        "## Projects",
        "",
        f"{summary}",
        "",
        "Full inventory with live git state → [`registry/REGISTRY.md`](registry/REGISTRY.md). "
        "That file is generated — run `python3 registry/render.py` after editing "
        "`registry/registry.toml`, and `python3 registry/reconcile.py` to check reality.",
        "",
        f"**Live on {meta.get('production_host', '?')}:** "
        + ", ".join(f"[{p['name']}]({p['url']})" for p in sorted(live, key=lambda x: x["name"])),
        "",
        END,
    ]
    return "\n".join(lines)


def splice_readme(block: str) -> str:
    readme = _readme()
    text = readme.read_text() if readme.exists() else "# Workspace\n"
    if BEGIN in text and END in text:
        pre = text[: text.index(BEGIN)]
        post = text[text.index(END) + len(END) :]
        return pre + block + post
    # First run: insert block after the top H1 (or prepend).
    if text.startswith("# "):
        nl = text.index("\n") + 1
        return text[:nl] + "\n" + block + "\n" + text[nl:]
    return block + "\n\n" + text


def run(check: bool = False) -> tuple[int, str]:
    """Render (or `check`) the generated docs. Returns (exit_code, text) — no printing,
    so the MCP layer never has to capture stdout."""
    meta, projects = load()
    reg = render_registry(meta, projects)
    readme = splice_readme(render_readme_block(meta, projects))

    if check:
        stale = []
        if not _registry_md().exists() or _registry_md().read_text() != reg:
            stale.append("registry/REGISTRY.md")
        if not _readme().exists() or _readme().read_text() != readme:
            stale.append("README.md")
        if stale:
            return 1, "STALE (run render): " + ", ".join(stale)
        return 0, "docs up to date"

    _registry_md().write_text(reg)
    _readme().write_text(readme)
    return 0, (
        f"wrote {_registry_md().relative_to(_root())} and {_readme().relative_to(_root())} ({len(projects)} projects)"
    )


def main(argv: list[str] | None = None) -> int:
    argv = list(argv) if argv is not None else sys.argv
    code, text = run(check="--check" in argv)
    print(text)
    return code


if __name__ == "__main__":
    raise SystemExit(main())
